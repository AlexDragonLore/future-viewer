import { expect, test } from '@playwright/test'

const key = process.env.FV_BIRTHDAY_QA_KEY
test.skip(!key, 'Requires the private local birthday backend and FV_BIRTHDAY_QA_KEY.')

test('secret invitation, hints, resume, five stages, gift and repeated visits', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`/birthday#key=${encodeURIComponent(key!)}`)
  await expect(page.getByRole('heading', { name: /Спроектируем/ })).toBeVisible()
  await expect(page.locator('#startup-splash')).toHaveCount(0)
  await expect(page).toHaveURL(/\/birthday$/)
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', 'noindex, nofollow')
  await page.screenshot({ path: testInfo.outputPath('birthday-invitation.png'), fullPage: true })
  await page.getByRole('button', { name: 'Начать маленькое приключение' }).click()
  await page.getByRole('button', { name: /Выбрать цвет фасада/ }).press('Enter')
  await expect(page.getByRole('status')).toContainText('Маленькая подсказка')
  await expect(page.locator('.score')).toContainText('0 / 500')
  await page.getByRole('button', { name: /Изучить грунт и нагрузки/ }).click()
  await expect(page.getByText('+100')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Превратим идею в пространство' })).toBeVisible()
  await expect(page.locator('#startup-splash')).toHaveCount(0)
  await expect(page.locator('.score')).toContainText('100 / 500')
  await page.screenshot({ path: testInfo.outputPath('birthday-game.png'), fullPage: true })
  const answers = ['Продумать связи между комнатами', 'Рассеянный свет и защита от бликов',
    'Растения по климату, свету и уходу', 'Представить свой день в этом доме']
  for (const [index, answer] of answers.entries()) {
    await page.getByRole('button', { name: new RegExp(answer) }).click()
    await expect(page.locator('.score')).toContainText(`${(index + 2) * 100} / 500`)
    await page.getByRole('button', { name: index === 3 ? 'Открыть мой подарок' : 'К следующему аркану' }).click()
  }
  await expect(page.getByRole('heading', { name: /Даша, это всё для тебя/ })).toBeVisible()
  await expect(page.locator('.gift-copy h2')).toContainText('15 000 ₽')
  await expect(page.locator('.postcard img')).toBeVisible()
  expect(await page.locator('.postcard img').evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0)
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Скачать сертификат' }).click()
  expect((await download).suggestedFilename()).toContain('15000')
  await page.getByRole('button', { name: 'Посмотреть сертификат и код' }).click()
  await expect(page.locator('.certificate-panel img')).toBeVisible()
  await page.getByRole('button', { name: 'Скрыть сертификат' }).click()
  await page.screenshot({ path: testInfo.outputPath('birthday-gift.png'), fullPage: true })
  await page.reload()
  await expect(page.getByRole('link', { name: 'Скачать сертификат' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.goto(`/birthday#key=${encodeURIComponent(key!)}`)
  await expect(page.getByRole('button', { name: 'Начать маленькое приключение' })).toBeVisible()
  await expect(page.locator('#startup-splash')).toHaveCount(0)
  await page.setViewportSize({ width: 320, height: 740 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('birthday-320px.png'), fullPage: true })
  expect(errors).toEqual([])
})

test('wrong invitation and a temporary network failure can be retried', async ({ page }) => {
  await page.goto('/birthday#key=incorrect-test-key')
  await expect(page.getByRole('alert')).toContainText('Ключ не подошёл')
  await expect(page).toHaveURL(/\/birthday$/)
  await page.getByLabel('Твой секретный ключ').fill(key!)
  await page.getByRole('button', { name: 'Открыть приглашение' }).click()
  await page.getByRole('button', { name: 'Начать маленькое приключение' }).click()
  await page.route('**/api/birthday/answer', route => route.abort('failed'), { times: 1 })
  await page.getByRole('button', { name: /Изучить грунт и нагрузки/ }).click()
  await expect(page.getByRole('alert')).toContainText('Проверь интернет')
  await page.getByRole('button', { name: /Изучить грунт и нагрузки/ }).click()
  await expect(page.getByText('+100')).toBeVisible()
  await expect(page.locator('.score')).toContainText('100 / 500')
})
